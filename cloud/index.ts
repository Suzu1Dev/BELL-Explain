import { resolve } from 'node:path';
import { CloudSyncStore, createCloudApp } from './app.js';

const token = process.env.BELL_SYNC_TOKEN || '';
if (!token || token.length < 32) throw new Error('Set BELL_SYNC_TOKEN to a secret generated by openssl rand -hex 32 before starting the sync server.');
const port = Number(process.env.PORT || 8080);
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('PORT must be between 1 and 65535.');
const store = new CloudSyncStore(resolve(process.env.BELL_SYNC_DB || 'data/cloud-sync.sqlite'));
const server = createCloudApp({store,token}).listen(port,process.env.HOST || '127.0.0.1',() => {
  console.log(`BELL sync server listening on port ${port}. Workspace ${store.workspaceId}`);
});
let stopping = false;
const stop = () => {
  if (stopping) return;stopping = true;
  server.close(() => {store.close();process.exit(0);});
  setTimeout(() => {server.closeAllConnections();},5000).unref();
};
process.on('SIGINT',stop);process.on('SIGTERM',stop);
